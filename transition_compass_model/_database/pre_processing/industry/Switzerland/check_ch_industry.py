"""CH industry model validation: energy vs SFOE, emissions vs BAFU, production vs literature.

Run from repo root: uv run python3 transition_compass_model/_database/pre_processing/industry/Switzerland/check_ch_industry.py
Requires 4 CSVs on Desktop generated by running industry_module.py with country_list=["Switzerland"].
"""

import os
import warnings

import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")

# ── Load model CSVs ──────────────────────────────────────────────────────────
df_nrg = pd.read_csv(
    os.path.expanduser("~/Desktop/industry_energy_bymatcarr.csv"), sep=";"
)
df_ems = pd.read_csv(
    os.path.expanduser("~/Desktop/industry_emissions_bygasmat.csv"), sep=";"
)
df_mat = pd.read_csv(
    os.path.expanduser("~/Desktop/industry_material_production_bytech.csv"), sep=";"
)

ch19_nrg = df_nrg[(df_nrg["Country"] == "Switzerland") & (df_nrg["Years"] == 2019)]
ch19_ems = df_ems[(df_ems["Country"] == "Switzerland") & (df_ems["Years"] == 2019)]
ch19_mat = df_mat[(df_mat["Country"] == "Switzerland") & (df_mat["Years"] == 2019)]

nrg_cols = [c for c in ch19_nrg.columns if c not in ["Country", "Years"]]
ems_cols = [c for c in ch19_ems.columns if c not in ["Country", "Years"]]
mat_cols = [c for c in ch19_mat.columns if c not in ["Country", "Years"]]


def nrg(*patterns):
    cols = [c for c in nrg_cols if any(p.lower() in c.lower() for p in patterns)]
    return float(ch19_nrg[cols].sum(axis=1).values[0])


def ems(*patterns):
    cols = [c for c in ems_cols if any(p.lower() in c.lower() for p in patterns)]
    return float(ch19_ems[cols].sum(axis=1).values[0])


def mat(*patterns):
    cols = [c for c in mat_cols if any(p.lower() in c.lower() for p in patterns)]
    return float(ch19_mat[cols].sum(axis=1).values[0])


# ── Load SFOE sector data ────────────────────────────────────────────────────
CARRIER_MAPPING = {
    "Elektrizität": "electricity",
    "Erdgas": "gas-ff-natural",
    "Heizöl extra-leicht": "liquid-ff-diesel",
    "Heizöl mittel und schwer": "liquid-ff-oil",
    "Industrieabfälle": "solid-waste",
    "Kohle": "solid-ff-coal",
    "Fernwärme (Bezug)": "electricity",
    "Holz": "solid-bio",
}
_base = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "data/energy-demand/",
)
_fp_new = _base + "8788-Publikationstabellen_DE_FR_IT_2013_bis_2024.xlsx"
_fp_old = _base + "12231-Publikationstabellen_DE_FR_IT_1999_bis_2013.xlsx"


def _read_sfoe_sheet(fp, sheet):
    df = pd.read_excel(fp, sheet_name=sheet)
    df.columns = df.iloc[2, :]
    df = df.iloc[3:, :]
    df = df[df["Secteur"] == "Industrie"]
    df = df[
        df["N° de branche"].apply(
            lambda x: isinstance(x, (int, float)) and 1 <= int(x) <= 11
        )
    ]
    yc = [c for c in df.columns if isinstance(c, (int, float)) and float(c) > 1900]
    dm = df.melt(
        id_vars=["N° de branche"], value_vars=yc, var_name="year", value_name="value_TJ"
    )
    dm["year"] = dm["year"].astype(int)
    dm["sector"] = dm["N° de branche"].astype(int)
    return dm[["year", "sector", "value_TJ"]]


dfs = []
for sheet in CARRIER_MAPPING:
    dn = _read_sfoe_sheet(_fp_new, sheet)
    do = _read_sfoe_sheet(_fp_old, sheet)
    dfs.append(pd.concat([dn, do[do["year"] < 2013]], ignore_index=True))

sfoe = pd.concat(dfs, ignore_index=True)
sfoe = sfoe.groupby(["year", "sector"], as_index=False)["value_TJ"].sum()
sfoe["TWh"] = sfoe["value_TJ"] / 3600  # 1 TWh = 3600 TJ
sfoe19 = sfoe[sfoe["year"] == 2019].set_index("sector")["TWh"]

# ── Load BAFU emissions (CO2 sheet) ──────────────────────────────────────────
_fp_bafu = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "data/emissions/Evolution_GHG_since_1990_2026-04.xlsx",
)
df_bafu = pd.read_excel(_fp_bafu, sheet_name="CO2", header=None)
_hrow = next(i for i, r in df_bafu.iterrows() if 1990.0 in r.values)
_yr_map = {
    int(v): j
    for j, v in enumerate(df_bafu.iloc[_hrow])
    if isinstance(v, float) and 1990 <= v <= 2024
}
_col19 = _yr_map[2019]
bafu = {}
for _, row in df_bafu.iterrows():
    cat = str(row.iloc[0]).strip()
    if cat in ("1A2", "2"):
        bafu[cat] = float(row.iloc[_col19])

# ── ENERGY TABLE ─────────────────────────────────────────────────────────────
print("=== ENERGY (TWh, Switzerland 2019) ===")
print(f"{'Sector':<26} {'Model':>8} {'SFOE':>8} {'Ratio':>7}  Notes")
nrg_rows = [
    ("Total S1-S11", nrg(*nrg_cols), sfoe19.sum(), "S1-S11 all carriers"),
    ("S1  FBT", nrg("fbt"), sfoe19.get(1, np.nan), ""),
    ("S2  Textiles", nrg("textiles"), sfoe19.get(2, np.nan), ""),
    (
        "S3  Paper/WWP",
        nrg("paper", "wwp", "timber"),
        sfoe19.get(3, np.nan),
        "S3=paper+printing+pulp+wood",
    ),
    ("S4  Chem", nrg("chem"), sfoe19.get(4, np.nan), "S4=chem+pharma"),
    (
        "S5  Cement",
        nrg("cement"),
        sfoe19.get(5, np.nan),
        "S5=cement+concrete (model: clinker only)",
    ),
    (
        "S6  Lime+Glass",
        nrg("lime", "glass"),
        sfoe19.get(6, np.nan),
        "S6=autres minéraux non ferreux",
    ),
    ("S7  Steel", nrg("steel"), sfoe19.get(7, np.nan), ""),
    ("S8  Al+Cu", nrg("aluminium", "copper"), sfoe19.get(8, np.nan), ""),
    ("S9  MAE", nrg("mae"), sfoe19.get(9, np.nan), ""),
    ("S10 Tra-equip", nrg("_tra_"), sfoe19.get(10, np.nan), ""),
    (
        "S11 OIS",
        nrg("_ois_", "_other_", "asphalt"),
        sfoe19.get(11, np.nan),
        "model OIS+other+asphalt",
    ),
]
for label, mv, sv, note in nrg_rows:
    sv = float(sv) if not (isinstance(sv, float) and np.isnan(sv)) else np.nan
    r = mv / sv if (sv and not np.isnan(sv) and sv > 0) else float("nan")
    print(f"{label:<26} {mv:>8.2f} {sv:>8.2f} {r:>7.2f}x  {note}")

# ── EMISSIONS TABLE ───────────────────────────────────────────────────────────
print()
print("=== EMISSIONS (MtCO2, Switzerland 2019) ===")
print(f"{'Category':<36} {'Model':>8} {'BAFU':>8}  Notes")
model_total = ems(*ems_cols)
bafu_1a2 = bafu.get("1A2", np.nan)
bafu_cat2 = bafu.get("2", np.nan)
bafu_total = bafu_1a2 + bafu_cat2
r_total = model_total / bafu_total
print(
    f"{'Total (combustion+process)':<36} {model_total:>8.2f} {bafu_total:>8.2f} {r_total:>7.2f}x  "
    f"BAFU 1A2+cat2 (1A2 incl. S12 construction ~0.1 MtCO2)"
)
print(
    f"{'  1A2 manufacturing combustion':<36} {'':>8} {bafu_1a2:>8.2f}        CO2 only"
)
print(
    f"{'  Cat 2 industrial processes':<36} {'':>8} {bafu_cat2:>8.2f}        CO2 only (no F-gases)"
)

# ── MATERIAL PRODUCTION TABLE ─────────────────────────────────────────────────
print()
print("=== MATERIAL PRODUCTION (kt, Switzerland 2019) ===")
print(f"{'Material':<20} {'Model':>10}  Reference")
prod_rows = [
    ("cement", mat("cement"), "4321 kt (Cemsuisse 2019; model covers clinker only)"),
    ("steel", mat("steel"), "~1000 kt (SwissSteel specialty — IO underestimate known)"),
    ("aluminium", mat("aluminium"), "~100 kt (Novelis Sierre, secondary scrap)"),
    ("copper", mat("copper"), "~50 kt (Swissmetal + recyclers)"),
    ("paper", mat("paper"), "~1600 kt (CEPI CH 2019)"),
    ("timber", mat("timber"), ""),
    ("wwp", mat("wwp"), ""),
    ("glass", mat("glass"), "~450 kt (est.)"),
    ("lime", mat("lime"), "~900 kt (Carmeuse + others)"),
]
for label, mv, ref in prod_rows:
    print(f"{label:<20} {mv:>10.0f}  {ref}")
